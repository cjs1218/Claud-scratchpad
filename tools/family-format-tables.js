// Code tables for docs/family-file-format.md, generated from the Navigator's data so the spec cannot drift from it.
// Run: node tools/family-format-tables.js           (rewrites the tables between the markers in the doc)
//      node tools/family-format-tables.js --check   (exits 1 if the doc is out of date; tests/check-data.js does this)
const fs = require('fs');
const path = require('path');
const load = require('../tests/load.js');

const ROOT = path.join(__dirname, '..');
const DOC = path.join(ROOT, 'docs/family-file-format.md');
const START = '<!-- codes:start (generated by tools/family-format-tables.js – do not edit by hand) -->';
const END = '<!-- codes:end -->';

function render() {
  const D = load(path.join(ROOT, 'cancer-family-history-navigator/js/data.js'));
  const html = fs.readFileSync(path.join(ROOT, 'cancer-family-history-navigator/index.html'), 'utf8');
  const sel = html.slice(html.indexOf('id="ancestry"'), html.indexOf('</select>', html.indexOf('id="ancestry"')));
  const ancestry = [...sel.matchAll(/<option value="([^"]*)">([^<]*)</g)].map(m => [m[1], m[2]]);
  // Which relatives a cousin, niece etc. can be linked to (PARENT_OF in eligibility.js, read from its source).
  const elig = fs.readFileSync(path.join(ROOT, 'cancer-family-history-navigator/js/eligibility.js'), 'utf8');
  const PARENT_OF = new Function(`return ${elig.match(/const PARENT_OF = (\{[\s\S]*?\});/)[1]}`)();
  const SIDE = { core: 'proband’s own generation', core2: 'proband’s siblings’ line', child: 'proband’s children', M: 'maternal', P: 'paternal', unknown: 'unknown' };
  const cell = s => String(s).replace(/\|/g, '\\|');
  const code = s => (s === '' ? '`""`' : '`' + s + '`');
  const L = [START, ''];

  L.push('### A. Relationship codes (`rel`)', '', 'Relationship to the proband. Where Sex is given, `sex` must match it. `parentId` may point to a person with one of the listed relationships.', '',
    '| Code | Meaning | Degree | Side | Sex | `parentId` may point to |', '|---|---|---|---|---|---|');
  for (const [k, label, deg, side, sex] of D.RELATIONS)
    L.push(`| ${code(k)} | ${cell(label)} | ${deg} | ${SIDE[side] || side} | ${sex || '–'} | ${PARENT_OF[k] ? PARENT_OF[k].map(code).join(', ') : '–'} |`);

  L.push('', '### B. Ancestry codes (`ancestry`)', '', '| Code | Meaning |', '|---|---|');
  for (const [k, label] of ancestry) L.push(`| ${code(k)} | ${cell(label)} |`);

  L.push('', '### C. Sites (`site`) and what each accepts', '',
    '| Site | Meaning | Tumour markers | `side` values | `count` |', '|---|---|---|---|---|');
  for (const [k, s] of Object.entries(D.SITES)) {
    const lat = D.LATERALITY[k];
    const sides = lat ? `${lat[1].map(code).join(', ')}${lat[0] === '*' ? '' : ` (only for ${lat[0].split('|').map(code).join(', ')})`}` : '–';
    const counted = k === 'polyps' ? 'yes (number of polyps)' : D.COUNTED[k] ? (D.COUNTED[k] === '*' ? 'yes' : `only for ${D.COUNTED[k].split('|').map(code).join(', ')}`) : '–';
    const markers = (s.markers || []).filter(m => m !== 'count');
    L.push(`| ${code(k)} | ${cell(s.label)} | ${markers.length ? markers.map(code).join(', ') : '–'} | ${sides} | ${counted} |`);
  }

  L.push('', '### D. Histology / type codes (`hist`) by site', '');
  for (const [k, s] of Object.entries(D.SITES)) {
    L.push(`**${code(k)} – ${cell(s.label)}**`, '', '| Code | Meaning |', '|---|---|');
    for (const [h, label] of s.hist) L.push(`| ${code(h)} | ${cell(label)} |`);
    L.push('');
  }

  L.push('### E. Tumour marker values', '', '`""` (or leaving the field out) means not done / not known.', '', '| Field | Values |', '|---|---|');
  for (const [k, m] of Object.entries(D.MARKER_OPTIONS))
    L.push(`| ${code(k)} | ${m.opts.filter(o => o[0] !== '').map(o => `${code(o[0])} ${cell(o[1])}`).join('; ')}${D.MARKER_HISTS[k] ? ` (only for ${D.MARKER_HISTS[k].map(code).join(', ')})` : ''} |`);
  L.push('', END);
  return L.join('\n');
}

function current(doc) {
  const a = doc.indexOf(START), b = doc.indexOf(END);
  return a < 0 || b < 0 ? null : doc.slice(a, b + END.length);
}

if (require.main === module) {
  const doc = fs.readFileSync(DOC, 'utf8');
  const now = current(doc), want = render();
  if (process.argv.includes('--check')) {
    if (now !== want) { console.log('docs/family-file-format.md code tables are out of date: run node tools/family-format-tables.js'); process.exit(1); }
    console.log('docs/family-file-format.md code tables are up to date');
  } else {
    if (now === null) throw new Error('markers not found in docs/family-file-format.md');
    fs.writeFileSync(DOC, doc.replace(now, want));
    console.log('Updated docs/family-file-format.md code tables');
  }
}
module.exports = { render, current, DOC };
